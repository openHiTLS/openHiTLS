/* exchange the 1,5,2,9,6,13,3,10,17,7,14,21 bit and the 28,32,20,27,24,31,12,19,26,16,23,30 bit of the key */
#define DES_KEY_TRANSFORM(key) \
    do { \
        key = (((key) >> 9) & 0x112244) |     \
              (((key) >> 18) & 0x1122) |      \
              (((key) >> 27) & 0x11) |        \
              ((key) & 0x11224488) |          \
              (((key) << 9) & 0x22448800) |   \
              (((key) << 18) & 0x44880000) |  \
              (((key) << 27) & 0x88000000);   \
    } while (0)

#define BIT_TRAN(l, r, t, n, m)                     \
    do {                                            \
        (t) = ((l) ^ ((l) << (n))) & (m);           \
        (l) = (l) ^ (t) ^ ((t) >> (n));             \
        (t) = ((r) ^ ((r) << (n))) & (m);           \
        (r) = (r) ^ (t) ^ ((t) >> (n));             \
    } while (0)

// IP, Initial permutation, the matrix is transposed from upper right to lower left.
// see https://en.wikipedia.org/wiki/DES_supplementary_material
#define D_IP(l, r, t)                                                                                                 \
    do {                                                                                                              \
        BIT_TRAN((l), (r), (t), 9, 0xaa00aa00);                                                                       \
        BIT_TRAN((l), (r), (t), 18, 0xcccc0000);                                                                      \
        (t) = ((l) & 0x0f0f0f0f) | (((r) << 4) & 0xf0f0f0f0);                                                         \
        (r) = (((l) >> 4) & 0x0f0f0f0f) | ((r) & 0xf0f0f0f0);                                                         \
        (l) = (((t) << 8) & 0xff000000) | (((t) << 16) & 0x00ff0000) | (((r) >> 8) & 0x0000ff00) | ((r) & 0xff);      \
        (r) = ((t) & 0xff000000) | (((t) << 8) & 0x00ff0000) | (((r) >> 16) & 0x0000ff00) | (((r) >> 8) & 0xff);      \
    } while (0)

// FP, IP^(-1), the reverse of IP.
#define D_FP(l, r, t)                                                                                                 \
    do {                                                                                                              \
        (l) = ((t) & 0xff000000) | (((r) >> 8) & 0x00ff0000) | (((t) >> 8) & 0x0000ff00) | (((r) >> 16) & 0xff);      \
        (r) = (((t) << 16) & 0xff000000) | (((r) << 8) & 0x00ff0000) | (((t) << 8) & 0x0000ff00) | ((r) & 0xff);      \
        BIT_TRAN((l), (r), (t), 9, 0xaa00aa00);                                                                       \
        BIT_TRAN((l), (r), (t), 18, 0xcccc0000);                                                                      \
        (t) = ((l) & 0x0f0f0f0f) | (((r) << 4) & 0xf0f0f0f0);                                                         \
        (r) = (((l) >> 4) & 0x0f0f0f0f) | ((r) & 0xf0f0f0f0);                                                         \
    } while (0)

#define DES_ENCRYPTION(l, r, key, n, ll, rr)                         \
    do {                                                             \
        (ll) = (r) ^ (key)[(n)];                                     \
        (rr) = (((r) >> 4) | ((r) << 28)) ^ (key)[(n) + 1];          \
        (l) ^= DES_SP_TRAN_TABLE[0][(rr) & 0x3f] | DES_SP_TRAN_TABLE[1][((rr) >> 8) & 0x3f] |           \
               DES_SP_TRAN_TABLE[2][((rr) >> 16) & 0x3f] | DES_SP_TRAN_TABLE[3][((rr) >> 24) & 0x3f] |  \
               DES_SP_TRAN_TABLE[4][(ll) & 0x3f] | DES_SP_TRAN_TABLE[5][((ll) >> 8) & 0x3f] |           \
               DES_SP_TRAN_TABLE[6][((ll) >> 16) & 0x3f] | DES_SP_TRAN_TABLE[7][((ll) >> 24) & 0x3f];   \
    } while (0)

#define DES_KEY_SHIFT(key, bit)                                \
    do {                                                       \
        (key) = (((key) >> (bit)) | ((key) << (28 - (bit))));  \
    } while (0)

