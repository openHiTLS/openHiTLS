int32_t CRYPT_DES_SetCryptKey(CRYPT_DES_Key *ctx, const uint8_t *key, uint32_t len)
{
    if (ctx == NULL || key == NULL) {
        BSL_ERR_PUSH_ERROR(CRYPT_NULL_INPUT);
        return CRYPT_NULL_INPUT;
    }

    if (len != DES_KEY_LEN) {
        BSL_ERR_PUSH_ERROR(CRYPT_DES_ERR_KEYLEN);
        return CRYPT_DES_ERR_KEYLEN;
    }
    // The key parity and weak key are not distinguished.
    if (ctx->keyNeedCheck != CRYPT_CTRL_DES_NOKEYCHECK) {
        if (DES_KeyValidityCheck(key) != CRYPT_SUCCESS) {
            BSL_ERR_PUSH_ERROR(CRYPT_DES_ERR_KEY);
            return CRYPT_DES_ERR_KEY;
        }
    }
    // It takes 16 rounds to generate 16 subkeys, and 1 or 2 bits are moved each time.
    const uint32_t shifts[16] = {1, 1, 2, 2, 2, 2, 2, 2, 1, 2, 2, 2, 2, 2, 2, 1};
    int32_t i;
    uint32_t originleft, originrignt;
    uint32_t leftKey, rightKey;
    uint32_t *keySchedule = (uint32_t *)ctx->ks;
    originleft = GET_UINT32_LE(key, 0);
    originrignt = GET_UINT32_LE(key, 4);      // Read from (4 + 1)th

    /* key schedule: PC-1: Input 64 bits and select 56 bits. */
    DES_KEY_TRANSFORM(originleft);
    DES_KEY_TRANSFORM(originrignt);
    rightKey = ((originrignt >> 4) ^ originleft) & 0x0f0f0f0f;      // originrignt shifts right by 4 bits
    originleft ^= rightKey;
    originrignt ^= (rightKey << 4);                                // rightKey shifts left by 4 bits
    // originrignt shifts left by 16 bits
    originrignt = (((originrignt & 0x000000ff) << 16) | (originrignt & 0x0000ff00) |
        ((originrignt & 0x00ff0000) >> 16) | ((originleft & 0xf0000000) >> 4)); // originrignt >> 16 bits then >> 4
    originleft &= 0x0fffffff;

    for (i = 0; i < 16; i++) {                                                              // 16 rounds of cycles
        /* Number of left shift bits, 16 cycles in total, determined by the number of cycles */
        DES_KEY_SHIFT(originleft, shifts[i]);
        DES_KEY_SHIFT(originrignt, shifts[i]);

        /* Generate the subkey */
        leftKey = DES_KEY_COMPRESSION[0][(originleft) & 0xff] |
            DES_KEY_COMPRESSION[1][(originleft >> 9) & 0xff] |                  // originleft shifts right by 9 bits
            DES_KEY_COMPRESSION[2][((originleft >> 18) & 0x7) |   // Queries the 2nd row of table, originleft >> 18 bits
            ((originleft >> 19) & 0x18) | ((originleft >> 20) & 0xe0)];         // originleft >> 19 bits then >> 20 bits

        rightKey = DES_KEY_COMPRESSION[3][(originrignt & 0x3f) | ((originrignt >> 1) & 0xc0)] | // Queries the 3rd row
            DES_KEY_COMPRESSION[4][((originrignt >> 10) & 0xf) | ((originrignt >> 11) & 0xf0)] | // 4th row, >>10, >>11
            DES_KEY_COMPRESSION[5][((originrignt >> 19) & 0x3f) | ((originrignt >> 20) & 0xc0)]; // 5th row, >>19, >>20

        /* key schedule: PC-2: Input 56 bits and select 48 bits. */
        *(keySchedule++) = (rightKey << 16L) | (leftKey & 0x0000ffff);  // rightKey shifts left by 16 bits
        leftKey = (leftKey >> 16) | (rightKey & 0xffff0000);         // leftKey shifts right by 16 bits
        *(keySchedule++) = leftKey;
    }
    BSL_SAL_CleanseData(&originleft, sizeof(uint32_t));
    BSL_SAL_CleanseData(&originrignt, sizeof(uint32_t));
    BSL_SAL_CleanseData(&leftKey, sizeof(uint32_t));
    BSL_SAL_CleanseData(&rightKey, sizeof(uint32_t));
    return CRYPT_SUCCESS;
}

int32_t CRYPT_DES_CheckWeakKey(const uint8_t *key, uint32_t len)
{
    uint32_t j;
    if (key == NULL || len != DES_KEY_LEN) {
        BSL_ERR_PUSH_ERROR(CRYPT_DES_ERR_LEN);
        return CRYPT_DES_ERR_LEN;
    }
    for (uint32_t i = 0; i < sizeof(DES_WEAK_KEY) / DES_BLOCK_BYTE_NUM; i++) {
        for (j = 0; j < DES_BLOCK_BYTE_NUM; j++) {
            if (key[j] != DES_WEAK_KEY[i][j]) {
                break;
            }
        }
        // j=DES_BLOCK_BYTE_NUM indicates that the key is the same as the weak key.
        if (j == DES_BLOCK_BYTE_NUM) {
            BSL_ERR_PUSH_ERROR(CRYPT_DES_ERR_KEY);
            return CRYPT_DES_ERR_KEY;
        }
    }
    return CRYPT_SUCCESS;
}

/* Key validity check. If the key is valid, 0 is returned.
   If the parity is incorrect, 1 is returned. If the password is weak, 2 is returned. */
static int32_t DES_KeyValidityCheck(const uint8_t key[8])
{
    // Check whether the parity bit is correct.
    for (uint32_t i = 0; i < DES_BLOCK_BYTE_NUM; i++) {
        if (key[i] != DES_ODD_PARITY_KEY[key[i]]) {
            BSL_ERR_PUSH_ERROR(CRYPT_DES_ERR_KEY);
            return CRYPT_DES_ERR_KEY;
        }
    }
    // Check whether the key is weak.
    return CRYPT_DES_CheckWeakKey(key, DES_KEY_LEN);
}

int32_t CRYPT_DES_KeyValidityCheck(const uint8_t *key, uint32_t len)
{
    if (key == NULL || len != DES_KEY_LEN) {
        BSL_ERR_PUSH_ERROR(CRYPT_DES_ERR_LEN);
        return CRYPT_DES_ERR_LEN;
    }
    // Check key
    return DES_KeyValidityCheck(key);
}

