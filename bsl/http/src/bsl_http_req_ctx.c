/* Return 0 when no deadline applies or it has not passed yet;
 * otherwise BSL_HTTP_ERR_TIMEOUT. */
static int32_t HttpCheckDeadline(HITLS_HTTP_ReqCtx *ctx)
{
    if (ctx->deadline == 0) {
        return 0;
    }
    BSL_TIME now = {0};
    if (BSL_SAL_SysTimeGet(&now) != BSL_SUCCESS) {
        return 0;
    }
    int64_t nowUtc = 0;
    if (BSL_SAL_DateToUtcTimeConvert(&now, &nowUtc) != BSL_SUCCESS) {
        return 0;
    }
    if (nowUtc >= ctx->deadline) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_TIMEOUT);
        return BSL_HTTP_ERR_TIMEOUT;
    }
    return 0;
}

/* Return IN_PROGRESS, or TIMEOUT when the transfer deadline has passed. */
static int32_t HttpInProgressOrTimeout(HITLS_HTTP_ReqCtx *ctx)
{
    if (HttpCheckDeadline(ctx) != 0) {
        return BSL_HTTP_ERR_TIMEOUT;
    }
    return BSL_HTTP_ERR_IN_PROGRESS;
}

static char *HttpStrDup(const char *s)
{
    if (s == NULL) {
        return NULL;
    }
    return (char *)BSL_SAL_Dump(s, (uint32_t)strlen(s) + 1);
}

/* Request target: reject whitespace and control characters, which would break
 * the request line framing (RFC 1945 Section 5.1: SP-separated, CRLF-terminated)
 * or allow header injection. The URI character set itself is not validated here
 * - a caller must pass a percent-encoded path. */
static bool HttpHasPathBadChar(const char *s)
{
    for (; *s != '\0'; s++) {
        unsigned char c = (unsigned char)*s;
        /* 0x00-0x1F: control characters (incl. CR/LF header injection).
         * 0x20: SP splits the request line into tokens. 0x7f: DEL. */
        if (c <= 0x20 || c == 0x7f) {
            return true;
        }
    }
    return false;
}

/* Field value: no control characters other than horizontal tab (RFC 7230 field-content). */
static bool HttpHasValueCtlChar(const char *s)
{
    for (; *s != '\0'; s++) {
        unsigned char c = (unsigned char)*s;
        /* 0x00-0x1F: control characters, except HTAB (0x09) which is valid
         * field-content (RFC 7230 field-content); CR/LF would inject headers.
         * 0x7f: DEL. */
        if ((c < 0x20 && c != '\t') || c == 0x7f) {
            return true;
        }
    }
    return false;
}

/* field-name = token (RFC 7230 Section 3.2.6). */
static bool HttpIsValidToken(const char *s)
{
    static const char tchar[] = "!#$%&'*+-.^_`|~"
                                "0123456789"
                                "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
                                "abcdefghijklmnopqrstuvwxyz";
    if (*s == '\0') {
        return false;
    }
    for (; *s != '\0'; s++) {
        if (strchr(tchar, *s) == NULL) {
            return false;
        }
    }
    return true;
}

static bool HttpStrCaseEqN(const char *a, const char *b, size_t n)
{
    for (size_t i = 0; i < n; i++) {
        if (tolower((unsigned char)a[i]) != tolower((unsigned char)b[i])) {
            return false;
        }
    }
    return true;
}

/* Case-insensitive media type match: a full-string match always passes;
 * otherwise parameters after ';' in the received value are ignored, but only
 * when the expected type carries no parameters itself and the value up to
 * ';' is exactly the expected string. */
static bool HttpMediaTypeMatch(const char *value, const char *expected)
{
    if (BSL_SAL_StrcaseCmp(value, expected) == 0) {
        return true;
    }
    if (strchr(expected, ';') != NULL) {
        return false;
    }
    const char *semicolon = strchr(value, ';');
    if (semicolon == NULL) {
        return false;
    }
    size_t prefixLen = (size_t)(semicolon - value);
    if (prefixLen != strlen(expected)) {
        return false;
    }
    return HttpStrCaseEqN(value, expected, prefixLen);
}

static bool HttpIsReservedHeader(const char *name)
{
    /* Content-Type/Content-Length are generated by HITLS_HTTP_ReqCtxSetReq;
     * Transfer-Encoding/Connection would conflict with the fixed Content-Length
     * + raw body framing this client emits (RFC 7230 Section 3.3.3). Host is
     * added via HITLS_HTTP_ReqCtxAddHeader like any other header. */
    return BSL_SAL_StrcaseCmp(name, "Content-Type") == 0 || BSL_SAL_StrcaseCmp(name, "Content-Length") == 0 ||
           BSL_SAL_StrcaseCmp(name, "Transfer-Encoding") == 0 || BSL_SAL_StrcaseCmp(name, "Connection") == 0;
}

/* Append a NUL-terminated string to the request header memory UIO. Returns
 * BSL_SUCCESS on success, BSL_MALLOC_FAIL when the memory UIO cannot grow. */
static int32_t HttpHdrAppend(HITLS_HTTP_ReqCtx *ctx, const char *s)
{
    uint32_t written = 0;
    if (BSL_UIO_Puts(ctx->reqHdrMem, s, &written) != BSL_SUCCESS || written != (uint32_t)strlen(s)) {
        BSL_ERR_PUSH_ERROR(BSL_MALLOC_FAIL);
        return BSL_MALLOC_FAIL;
    }
    return BSL_SUCCESS;
}

/* Mirror of the internal BSL_BufMem returned by the memory UIO (same layout:
 * { size_t length; char *data; size_t max; }) so the header content can be read
 * without depending on an internal header. */
typedef struct {
    size_t length;
    char *data;
    size_t max;
} HttpBufMem;

const uint8_t *HttpGetRespBody(const HITLS_HTTP_ReqCtx *ctx, uint32_t *len)
{
    if (ctx == NULL || ctx->respMem == NULL || len == NULL) {
        return NULL;
    }
    HttpBufMem *bm = NULL;
    if (BSL_UIO_Ctrl(ctx->respMem, BSL_UIO_MEM_GET_PTR, (int32_t)sizeof(HttpBufMem *), &bm) != BSL_SUCCESS ||
        bm == NULL) {
        return NULL;
    }
    *len = (uint32_t)bm->length;
    return (const uint8_t *)bm->data;
}

/* Write the request line "METHOD <path> HTTP/1.0\r\n" into the header memory UIO.
 * Only POST is supported today; adding a method means extending the enum, the
 * check in HITLS_HTTP_ReqCtxNew and this mapping. */
static int32_t HttpWriteRequestLine(HITLS_HTTP_ReqCtx *ctx)
{
    char line[HITLS_HTTP_MAX_PATH_LEN + 32];
    const char *methodStr = "POST"; /* HITLS_HTTP_METHOD_POST. */
    int n = snprintf(line, sizeof(line), "%s %s HTTP/1.0\r\n", methodStr, ctx->path);
    if (n <= 0 || (uint32_t)n >= sizeof(line)) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    return HttpHdrAppend(ctx, line);
}

HITLS_HTTP_ReqCtx *HITLS_HTTP_ReqCtxNew(BSL_UIO *uio, int32_t method, const char *path)
{
    HITLS_HTTP_ReqCtx *ctx = NULL;
    if (uio == NULL || path == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_NULL_INPUT);
        goto EXIT;
    }
    /* Only POST is supported for now; other methods are reserved for extension. */
    if (method != HITLS_HTTP_METHOD_POST) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        goto EXIT;
    }
    if (path[0] == '\0' || strlen(path) > HITLS_HTTP_MAX_PATH_LEN || HttpHasPathBadChar(path)) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        goto EXIT;
    }
    ctx = BSL_SAL_Calloc(1, sizeof(HITLS_HTTP_ReqCtx));
    if (ctx == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_MALLOC_FAIL);
        goto EXIT;
    }
    ctx->uio = uio;
    ctx->method = method;
    ctx->path = HttpStrDup(path);
    if (ctx->path == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_MALLOC_FAIL);
        goto EXIT;
    }
    /* The request header is accumulated in a memory UIO: the request line is
     * written here, custom headers and CT/CL are appended by AddHeader/SetReq.
     * The response body is accumulated in a second memory UIO (grown internally,
     * capped at maxRespLen by the read state handler). */
    ctx->reqHdrMem = BSL_UIO_New(BSL_UIO_MemMethod());
    if (ctx->reqHdrMem == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_MALLOC_FAIL);
        goto EXIT;
    }
    ctx->respMem = BSL_UIO_New(BSL_UIO_MemMethod());
    if (ctx->respMem == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_MALLOC_FAIL);
        goto EXIT;
    }
    if (HttpWriteRequestLine(ctx) != BSL_SUCCESS) {
        goto EXIT; /* HttpWriteRequestLine already pushed the error. */
    }
    /* No Host header by default: HTTP/1.0 (RFC 1945) does not require one, and
     * the uio peer IP is not a meaningful authority. Callers that need a Host
     * header add it explicitly with HITLS_HTTP_ReqCtxAddHeader before the transfer. */
    ctx->maxRespLen = HITLS_HTTP_DEFAULT_MAX_RESP_LEN;
    ctx->maxHdrLines = HITLS_HTTP_DEFAULT_MAX_RESP_HDR_LINES;
    ctx->maxLineLen = HITLS_HTTP_MAX_LINE_LEN;
    ctx->lineBuf = BSL_SAL_Malloc(ctx->maxLineLen);
    if (ctx->lineBuf == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_MALLOC_FAIL);
        goto EXIT;
    }
    ctx->state = HITLS_HTTP_STATE_INIT;
    ctx->firstHdrLine = 1;
    return ctx;
EXIT:
    if (ctx != NULL) {
        BSL_UIO_Free(ctx->respMem);
        BSL_UIO_Free(ctx->reqHdrMem);
        BSL_SAL_FREE(ctx->lineBuf);
        BSL_SAL_FREE(ctx->path);
        BSL_SAL_FREE(ctx);
    }
    return NULL;
}

void HITLS_HTTP_ReqCtxFree(HITLS_HTTP_ReqCtx *ctx)
{
    if (ctx == NULL) {
        return;
    }
    BSL_SAL_FREE(ctx->path);
    BSL_UIO_Free(ctx->reqHdrMem);
    BSL_UIO_Free(ctx->respMem);
    BSL_SAL_FREE(ctx->reqBody.data);
    BSL_SAL_FREE(ctx->expectedCt);
    BSL_SAL_FREE(ctx->respCt);
    BSL_SAL_FREE(ctx->lineBuf);
    BSL_SAL_FREE(ctx);
}

int32_t HITLS_HTTP_ReqCtxSetReq(HITLS_HTTP_ReqCtx *ctx, const char *contentType, const uint8_t *req, uint32_t reqLen)
{
    if (ctx == NULL || contentType == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    if (req == NULL && reqLen != 0) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    /* The request body can be set only once, before the transfer starts; a
     * repeated call (after a completed or in-flight transfer) is rejected. */
    if (ctx->reqSet) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    /* Reject empty and whitespace-only Content-Type: either would emit a
     * degenerate "Content-Type: \r\n" / "Content-Type:  \r\n" framing header
     * (RFC 7231 requires a non-empty media type). */
    const char *ct = contentType;
    while (*ct == ' ' || *ct == '\t') {
        ct++;
    }
    if (*ct == '\0' || strlen(contentType) > HITLS_HTTP_MAX_CONTENT_TYPE_LEN || HttpHasValueCtlChar(contentType)) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    /* Copy the request body before touching the header UIO: an allocation
     * failure then leaves no partial framing header behind. */
    uint8_t *newBody = NULL;
    if (req != NULL && reqLen > 0) {
        newBody = BSL_SAL_Dump(req, reqLen);
        if (newBody == NULL) {
            BSL_ERR_PUSH_ERROR(BSL_MALLOC_FAIL);
            return BSL_MALLOC_FAIL;
        }
    }
    /* Append both framing headers in a single write (all-or-nothing): a partial
     * append would leave a stale Content-Type/Content-Length in the header UIO
     * that a retry of SetReq would then duplicate (and, with a different
     * reqLen, would conflict with itself). */
    char line[HITLS_HTTP_MAX_CONTENT_TYPE_LEN + 64];
    int n = snprintf(line, sizeof(line), "Content-Type: %s\r\nContent-Length: %u\r\n", contentType, (unsigned)reqLen);
    if (n <= 0 || (uint32_t)n >= sizeof(line)) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        BSL_SAL_FREE(newBody);
        return BSL_HTTP_ERR_PARAM;
    }
    if (HttpHdrAppend(ctx, line) != BSL_SUCCESS) {
        BSL_SAL_FREE(newBody);
        return BSL_MALLOC_FAIL;
    }
    ctx->reqBody.data = newBody;
    ctx->reqBody.dataLen = reqLen;
    ctx->reqBodySent = 0;
    ctx->reqSet = 1;
    ctx->state = HITLS_HTTP_STATE_INIT;
    return BSL_SUCCESS;
}

int32_t HITLS_HTTP_ReqCtxAddHeader(HITLS_HTTP_ReqCtx *ctx, const char *name, const char *value)
{
    if (ctx == NULL || name == NULL || value == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    /* Headers can only be added while the context is in the INIT (configuration)
     * state, i.e. before the transfer starts. */
    if (ctx->state != HITLS_HTTP_STATE_INIT) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    if (strlen(name) > HITLS_HTTP_MAX_HDR_NAME_LEN || strlen(value) > HITLS_HTTP_MAX_HDR_VALUE_LEN) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    if (!HttpIsValidToken(name) || HttpHasValueCtlChar(value)) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    if (HttpIsReservedHeader(name)) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    if (ctx->reqHdrCount >= ctx->maxHdrLines) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    /* Append "name: value\r\n" directly into the header memory UIO. */
    char line[HITLS_HTTP_MAX_HDR_NAME_LEN + HITLS_HTTP_MAX_HDR_VALUE_LEN + 16];
    int n = snprintf(line, sizeof(line), "%s: %s\r\n", name, value);
    if (n <= 0 || (uint32_t)n >= sizeof(line)) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    if (HttpHdrAppend(ctx, line) != BSL_SUCCESS) {
        return BSL_MALLOC_FAIL;
    }
    ctx->reqHdrCount++;
    return BSL_SUCCESS;
}

/* Validate a uint32_t ctrl value (pointer and size); on success returns the
 * value pointer, otherwise NULL with the PARAM error pushed. */
static uint32_t *HttpCtrlU32Param(void *val, uint32_t valLen)
{
    if (val == NULL || valLen != sizeof(uint32_t)) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return NULL;
    }
    return (uint32_t *)val;
}

/* HITLS_HTTP_CTRL_SET_MAX_RESP_LEN / SET_MAX_RESP_HDR_LINES: read a uint32
 * ctrl value into a field. A 0 limit is rejected: it would reject every real
 * response, and failing fast beats silently substituting a default. The
 * dispatcher has already enforced the INIT-state requirement. */
static int32_t HttpCtrlSetU32(void *val, uint32_t valLen, uint32_t *field)
{
    uint32_t *v = HttpCtrlU32Param(val, valLen);
    if (v == NULL) {
        return BSL_HTTP_ERR_PARAM;
    }
    if (*v == 0) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    *field = *v;
    return BSL_SUCCESS;
}

/* HITLS_HTTP_CTRL_SET_MAX_LINE_LEN: resize the dynamic response line buffer.
 * Kept separate from the plain uint32 setters because it allocates. The
 * dispatcher has already enforced the INIT-state requirement. */
static int32_t HttpCtrlSetMaxLineLen(HITLS_HTTP_ReqCtx *ctx, void *val, uint32_t valLen)
{
    uint32_t *v = HttpCtrlU32Param(val, valLen);
    if (v == NULL) {
        return BSL_HTTP_ERR_PARAM;
    }
    if (*v < HITLS_HTTP_MIN_LINE_LEN || *v > HITLS_HTTP_MAX_LINE_LEN) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    /* Resize the dynamic line buffer. The context is in INIT, so the buffer holds
     * no partial line yet and is simply replaced; the field is updated only after
     * a successful allocation. */
    uint8_t *nb = BSL_SAL_Malloc(*v);
    if (nb == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_MALLOC_FAIL);
        return BSL_MALLOC_FAIL;
    }
    BSL_SAL_FREE(ctx->lineBuf);
    ctx->lineBuf = nb;
    ctx->maxLineLen = *v;
    return BSL_SUCCESS;
}

/* HITLS_HTTP_CTRL_SET_EXPECTED_CT: set or clear the expected response Content-Type. */
static int32_t HttpCtrlSetExpectedCt(HITLS_HTTP_ReqCtx *ctx, void *val, uint32_t valLen)
{
    /* The command takes a NUL-terminated string; a non-zero length from a caller
     * that did not pass a terminated buffer would be read past its end by strlen. */
    if (valLen != 0) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    const char *ct = (const char *)val;
    if (val != NULL && (strlen(ct) > HITLS_HTTP_MAX_CONTENT_TYPE_LEN || HttpHasValueCtlChar(ct))) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    char *dup = NULL;
    if (val != NULL) {
        dup = HttpStrDup(ct);
        if (dup == NULL) {
            BSL_ERR_PUSH_ERROR(BSL_MALLOC_FAIL);
            return BSL_MALLOC_FAIL;
        }
    }
    BSL_SAL_FREE(ctx->expectedCt);
    ctx->expectedCt = dup;
    return BSL_SUCCESS;
}

/* HITLS_HTTP_CTRL_SET_TIMEOUT: set the absolute transfer deadline (UTC seconds). */
static int32_t HttpCtrlSetTimeout(HITLS_HTTP_ReqCtx *ctx, void *val, uint32_t valLen)
{
    if (val == NULL || valLen != sizeof(uint32_t)) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    if (*(uint32_t *)val == 0) {
        ctx->deadline = 0;
        return BSL_SUCCESS;
    }
    BSL_TIME now = {0};
    int64_t nowUtc = 0;
    if (BSL_SAL_SysTimeGet(&now) != BSL_SUCCESS || BSL_SAL_DateToUtcTimeConvert(&now, &nowUtc) != BSL_SUCCESS) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    ctx->deadline = nowUtc + (int64_t) * (uint32_t *)val;
    return BSL_SUCCESS;
}

/* True for commands that modify transfer settings. */
static bool HttpIsSetCmd(int32_t cmd)
{
    switch (cmd) {
        case HITLS_HTTP_CTRL_SET_MAX_RESP_LEN:
        case HITLS_HTTP_CTRL_SET_MAX_RESP_HDR_LINES:
        case HITLS_HTTP_CTRL_SET_MAX_LINE_LEN:
        case HITLS_HTTP_CTRL_SET_EXPECTED_CT:
        case HITLS_HTTP_CTRL_SET_TIMEOUT:
            return true;
        default:
            return false;
    }
}

/* HITLS_HTTP_CTRL_GET_*: write a read-only uint32 value into the caller's
 * buffer. Callable at any time. */
static int32_t HttpCtrlGetU32(void *val, uint32_t valLen, uint32_t value)
{
    if (val == NULL || valLen != sizeof(uint32_t)) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    *(uint32_t *)val = value;
    return BSL_SUCCESS;
}

int32_t HITLS_HTTP_ReqCtxCtrl(HITLS_HTTP_ReqCtx *ctx, int32_t cmd, void *val, uint32_t valLen)
{
    if (ctx == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    /* SET operations change transfer settings and apply only while the context is
     * in the INIT (configuration) state; GET operations are read-only. */
    if (HttpIsSetCmd(cmd) && ctx->state != HITLS_HTTP_STATE_INIT) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    switch (cmd) {
        case HITLS_HTTP_CTRL_GET_MAX_RESP_LEN:
            return HttpCtrlGetU32(val, valLen, ctx->maxRespLen);
        case HITLS_HTTP_CTRL_GET_MAX_RESP_HDR_LINES:
            return HttpCtrlGetU32(val, valLen, ctx->maxHdrLines);
        case HITLS_HTTP_CTRL_GET_MAX_LINE_LEN:
            return HttpCtrlGetU32(val, valLen, ctx->maxLineLen);
        case HITLS_HTTP_CTRL_GET_RESP_STATUS:
            return HttpCtrlGetU32(val, valLen, ctx->respStatusCode);
        case HITLS_HTTP_CTRL_SET_MAX_RESP_LEN:
            return HttpCtrlSetU32(val, valLen, &ctx->maxRespLen);
        case HITLS_HTTP_CTRL_SET_MAX_RESP_HDR_LINES:
            return HttpCtrlSetU32(val, valLen, &ctx->maxHdrLines);
        case HITLS_HTTP_CTRL_SET_MAX_LINE_LEN:
            return HttpCtrlSetMaxLineLen(ctx, val, valLen);
        case HITLS_HTTP_CTRL_SET_EXPECTED_CT:
            return HttpCtrlSetExpectedCt(ctx, val, valLen);
        case HITLS_HTTP_CTRL_SET_TIMEOUT:
            return HttpCtrlSetTimeout(ctx, val, valLen);
        default:
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
            return BSL_HTTP_ERR_PARAM;
    }
}

/* Append the terminating blank line (end of request headers) to the header
 * memory UIO, once. */
static int32_t HttpTerminateHdr(HITLS_HTTP_ReqCtx *ctx)
{
    if (ctx->hdrTerminated) {
        return BSL_SUCCESS;
    }
    int32_t ret = HttpHdrAppend(ctx, "\r\n");
    if (ret != BSL_SUCCESS) {
        return ret;
    }
    ctx->hdrTerminated = 1;
    return BSL_SUCCESS;
}

static int32_t HttpWriteRequestHeader(HITLS_HTTP_ReqCtx *ctx)
{
    int32_t ret = HttpTerminateHdr(ctx);
    if (ret != BSL_SUCCESS) {
        return ret;
    }
    /* The request header is read straight out of the memory UIO (GET_PTR gives
     * a non-consuming view, so a partial write can retry from reqHdrSent). */
    HttpBufMem *bm = NULL;
    ret = BSL_UIO_Ctrl(ctx->reqHdrMem, BSL_UIO_MEM_GET_PTR, (int32_t)sizeof(HttpBufMem *), &bm);
    if (ret != BSL_SUCCESS) {
        return ret;
    }
    if (bm == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_SAL_ERR_UNKNOWN);
        return BSL_SAL_ERR_UNKNOWN;
    }
    uint32_t hdrLen = (uint32_t)bm->length;
    while (ctx->reqHdrSent < hdrLen) {
        /* Hard deadline: fail once the transfer has exceeded its allowed time,
         * even while data is flowing (not only at would-block points). */
        if (HttpCheckDeadline(ctx) != 0) {
            return BSL_HTTP_ERR_TIMEOUT;
        }
        uint32_t writeLen = 0;
        int32_t writeRet = BSL_UIO_Write(ctx->uio, bm->data + ctx->reqHdrSent, hdrLen - ctx->reqHdrSent, &writeLen);
        if (writeRet == BSL_UIO_IO_BUSY) {
            /* The buffered UIO wrapper reports a full/failed flush as BUSY:
             * the transfer is still in progress, not a hard I/O error. */
            return HttpInProgressOrTimeout(ctx);
        }
        if (writeRet != BSL_SUCCESS) {
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_IO);
            return BSL_HTTP_ERR_IO;
        }
        if (writeLen == 0) {
            return HttpInProgressOrTimeout(ctx);
        }
        ctx->reqHdrSent += writeLen;
    }
    ctx->state = HITLS_HTTP_STATE_WRITE_REQ;
    return BSL_SUCCESS;
}

static int32_t HttpWriteRequestBody(HITLS_HTTP_ReqCtx *ctx)
{
    while (ctx->reqBodySent < ctx->reqBody.dataLen) {
        /* Hard deadline: fail once the transfer has exceeded its allowed time. */
        if (HttpCheckDeadline(ctx) != 0) {
            return BSL_HTTP_ERR_TIMEOUT;
        }
        uint32_t writeLen = 0;
        int32_t ret = BSL_UIO_Write(ctx->uio, ctx->reqBody.data + ctx->reqBodySent,
                                    ctx->reqBody.dataLen - ctx->reqBodySent, &writeLen);
        if (ret == BSL_UIO_IO_BUSY) {
            return HttpInProgressOrTimeout(ctx);
        }
        if (ret != BSL_SUCCESS) {
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_IO);
            return BSL_HTTP_ERR_IO;
        }
        if (writeLen == 0) {
            return HttpInProgressOrTimeout(ctx);
        }
        ctx->reqBodySent += writeLen;
    }
    ctx->state = HITLS_HTTP_STATE_FLUSH;
    return BSL_SUCCESS;
}

static int32_t HttpFlush(HITLS_HTTP_ReqCtx *ctx)
{
    int32_t ret = BSL_UIO_Ctrl(ctx->uio, BSL_UIO_FLUSH, 0, NULL);
    if (ret == BSL_SUCCESS) {
        /* The write phase may have consumed most of the transfer deadline
         * (partial writes + retries), so check it before starting to read. */
        if (HttpCheckDeadline(ctx) != 0) {
            return BSL_HTTP_ERR_TIMEOUT;
        }
        ctx->state = HITLS_HTTP_STATE_READ_HDR;
        return BSL_SUCCESS;
    }
    if (ret == BSL_UIO_IO_BUSY) {
        return HttpInProgressOrTimeout(ctx);
    }
    BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_IO);
    return BSL_HTTP_ERR_IO;
}

/* Extract one complete line (NUL-terminated, CR/LF stripped) in place at the
 * start of lineBuf. Returns 1 when a line is available, 0 otherwise. The
 * terminator may be overwritten by the NUL, so the byte count through the '\n'
 * is recorded in lineConsumed for HttpDropLine. A line is delimited by '\n';
 * a preceding '\r' is stripped, while a bare '\n' (without a preceding '\r')
 * is accepted as a tolerant parse of a non-CRLF terminator. */
static int32_t HttpExtractLine(HITLS_HTTP_ReqCtx *ctx)
{
    uint32_t idx = 0;
    while (idx < ctx->lineBufLen && ctx->lineBuf[idx] != '\n') {
        idx++;
    }
    if (idx == ctx->lineBufLen) {
        return 0;
    }
    uint32_t lineEnd = idx;
    if (lineEnd > 0 && ctx->lineBuf[lineEnd - 1] == '\r') {
        lineEnd--;
    }
    ctx->lineBuf[lineEnd] = '\0';
    ctx->lineConsumed = idx + 1;
    return 1;
}

/* Drop the line at the start of lineBuf (counted through its '\n'). */
static void HttpDropLine(HITLS_HTTP_ReqCtx *ctx)
{
    uint32_t consumed = ctx->lineConsumed;
    if (consumed > ctx->lineBufLen) {
        consumed = ctx->lineBufLen;
    }
    uint32_t remain = ctx->lineBufLen - consumed;
    if (remain > 0) {
        (void)memmove(ctx->lineBuf, ctx->lineBuf + consumed, remain);
    }
    ctx->lineBufLen = remain;
    ctx->lineConsumed = 0;
}

/* End of response headers (blank line received): an expected Content-Type that
 * never arrived is a mismatch; a declared body beyond the cap is rejected.
 * Transitions the state machine to READ_BODY. */
static int32_t HttpEndResponseHeader(HITLS_HTTP_ReqCtx *ctx)
{
    if (ctx->expectedCt != NULL && ctx->respCt == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_CONTENT_TYPE);
        return BSL_HTTP_ERR_CONTENT_TYPE;
    }
    if (ctx->hasContentLength && ctx->respContentLength > ctx->maxRespLen) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_TOO_LARGE);
        return BSL_HTTP_ERR_RESP_TOO_LARGE;
    }
    ctx->state = HITLS_HTTP_STATE_READ_BODY;
    return BSL_SUCCESS;
}

/* Process a parsed response header (non-status, non-blank line). Only
 * Content-Type and Content-Length frame/validate the body; other headers are
 * ignored (Transfer-Encoding is not inspected: an undecoded chunked stream
 * reaches the caller raw). */
static int32_t HttpProcessResponseHeaderLine(HITLS_HTTP_ReqCtx *ctx, const char *name, const char *value)
{
    if (BSL_SAL_StrcaseCmp(name, "Content-Type") == 0) {
        if (ctx->expectedCt != NULL && !HttpMediaTypeMatch(value, ctx->expectedCt)) {
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_CONTENT_TYPE);
            return BSL_HTTP_ERR_CONTENT_TYPE;
        }
        /* Content-Type is a single-value field (not a comma-separated list,
         * RFC 7230 Sections 3.2.2/3.3.1), so a repeated header with a
         * different value is a malformed response: reject, like the repeated
         * Content-Length consistency check below. An identical repeat is
         * tolerated. */
        if (ctx->respCt != NULL && BSL_SAL_StrcaseCmp(ctx->respCt, value) != 0) {
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_PARSE);
            return BSL_HTTP_ERR_RESP_PARSE;
        }
        char *dup = HttpStrDup(value);
        if (dup == NULL) {
            BSL_ERR_PUSH_ERROR(BSL_MALLOC_FAIL);
            return BSL_MALLOC_FAIL;
        }
        BSL_SAL_FREE(ctx->respCt);
        ctx->respCt = dup;
    } else if (BSL_SAL_StrcaseCmp(name, "Content-Length") == 0) {
        uint32_t len = 0;
        if (HttpParseDecimal(value, &len) != HITLS_HTTP_DECIMAL_PARSE_OK) {
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_PARSE);
            return BSL_HTTP_ERR_RESP_PARSE;
        }
        /* RFC 7230 Section 3.3.3: a repeated Content-Length must repeat the
         * same value, otherwise the body framing is ambiguous - reject. */
        if (ctx->hasContentLength && ctx->respContentLength != len) {
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_PARSE);
            return BSL_HTTP_ERR_RESP_PARSE;
        }
        ctx->respContentLength = len;
        ctx->hasContentLength = 1;
    }
    return BSL_SUCCESS;
}

static int32_t HttpProcessHeaderLine(HITLS_HTTP_ReqCtx *ctx)
{
    char *line = (char *)ctx->lineBuf;
    if (ctx->firstHdrLine) {
        if (HttpParseStatusLine(line, &ctx->respStatusCode) != HITLS_HTTP_STATUS_PARSE_OK) {
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_PARSE);
            return BSL_HTTP_ERR_RESP_PARSE;
        }
        /* Only a 200 OK response carries the expected body. Any other status
         * (3xx redirect, 4xx/5xx error) means the server did not produce an
         * OCSP response, so the transfer stops here - the error body is not
         * read (the connection is closed by HTTP/1.0 anyway). */
        if (ctx->respStatusCode != HITLS_HTTP_STATUS_OK) {
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_STATUS);
            return BSL_HTTP_ERR_RESP_STATUS;
        }
        ctx->firstHdrLine = 0;
        return BSL_SUCCESS;
    }
    if (*line == '\0') {
        return HttpEndResponseHeader(ctx);
    }
    ctx->hdrLineCount++;
    /* Header lines past the configured bound are rejected. */
    if (ctx->hdrLineCount > ctx->maxHdrLines) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_HDR_LINES);
        return BSL_HTTP_ERR_RESP_HDR_LINES;
    }
    const char *name = NULL;
    const char *value = NULL;
    int32_t parseRet = HttpParseHeaderLine(line, &name, &value);
    if (parseRet == HITLS_HTTP_HEADER_PARSE_IGNORE) {
        /* Such lines are dropped without processing them. */
        return BSL_SUCCESS;
    }
    if (parseRet != HITLS_HTTP_HEADER_PARSE_OK) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_PARSE);
        return BSL_HTTP_ERR_RESP_PARSE;
    }
    return HttpProcessResponseHeaderLine(ctx, name, value);
}

/* Append |take| bytes into the response body memory UIO, bounded by maxRespLen.
 * A body that exceeds the cap is rejected (a close-delimited body may be probed
 * for EOF first by the caller). */
static int32_t HttpAppendRespBody(HITLS_HTTP_ReqCtx *ctx, const uint8_t *data, uint32_t take)
{
    if ((uint64_t)ctx->respBodyLen + take > ctx->maxRespLen) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_TOO_LARGE);
        return BSL_HTTP_ERR_RESP_TOO_LARGE;
    }
    uint32_t written = 0;
    if (BSL_UIO_Write(ctx->respMem, data, take, &written) != BSL_SUCCESS || written != take) {
        BSL_ERR_PUSH_ERROR(BSL_MALLOC_FAIL);
        return BSL_MALLOC_FAIL;
    }
    ctx->respBodyLen += take;
    return BSL_SUCCESS;
}

/* Move bytes left over from response header reading into the response body (a
 * chunk read past the end of the headers already belongs to the body). There is
 * at most one such batch - header reads finish at the end-of-headers transition
 * - so the caller invokes this exactly once, right after dropping the blank
 * line. Returns BSL_SUCCESS or an error. */
static int32_t HttpAppendLineBufBody(HITLS_HTTP_ReqCtx *ctx)
{
    uint32_t take = ctx->lineBufLen;
    if (take == 0) {
        return BSL_SUCCESS;
    }
    if (ctx->hasContentLength && (uint64_t)ctx->respBodyLen + take > ctx->respContentLength) {
        take = ctx->respContentLength - ctx->respBodyLen;
    }
    int32_t appRet = HttpAppendRespBody(ctx, (const uint8_t *)ctx->lineBuf, take);
    if (appRet != BSL_SUCCESS) {
        return appRet;
    }
    ctx->lineBufLen -= take;
    if (ctx->lineBufLen > 0) {
        (void)memmove(ctx->lineBuf, ctx->lineBuf + take, ctx->lineBufLen);
    }
    return BSL_SUCCESS;
}

static int32_t HttpReadResponseHeader(HITLS_HTTP_ReqCtx *ctx)
{
    for (;;) {
        if (HttpExtractLine(ctx) == 1) {
            int32_t r = HttpProcessHeaderLine(ctx);
            if (r != BSL_SUCCESS) {
                return r;
            }
            HttpDropLine(ctx);
            if (ctx->state != HITLS_HTTP_STATE_READ_HDR) {
                /* End of headers: bytes read past the blank line belong to the
                 * body. This transition happens exactly once per transfer. */
                int32_t leftoverRet = HttpAppendLineBufBody(ctx);
                if (leftoverRet != BSL_SUCCESS) {
                    return leftoverRet;
                }
                return BSL_SUCCESS;
            }
            continue;
        }
        uint8_t chunk[HITLS_HTTP_READ_CHUNK];
        uint32_t readLen = 0;
        /* Cap the read at the space left in the line buffer so a line that ends
         * exactly at the limit (e.g. maxLineLen bytes incl. the terminator) is
         * accepted instead of being rejected by the chunk size alone. */
        uint32_t room = ctx->maxLineLen - ctx->lineBufLen;
        uint32_t want = (room < HITLS_HTTP_READ_CHUNK) ? room : HITLS_HTTP_READ_CHUNK;
        if (want == 0) {
            /* The buffer is full without a terminator: the line exceeds the limit. */
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_PARSE);
            return BSL_HTTP_ERR_RESP_PARSE;
        }
        /* Hard deadline: fail once the transfer has exceeded its allowed time. */
        if (HttpCheckDeadline(ctx) != 0) {
            return BSL_HTTP_ERR_TIMEOUT;
        }
        int32_t ret = BSL_UIO_Read(ctx->uio, chunk, want, &readLen);
        if (ret == BSL_SUCCESS) {
            if (readLen > 0) {
                (void)memcpy(ctx->lineBuf + ctx->lineBufLen, chunk, readLen);
                ctx->lineBufLen += readLen;
                continue;
            }
            return HttpInProgressOrTimeout(ctx);
        }
        if (ret == BSL_UIO_IO_BUSY) {
            return HttpInProgressOrTimeout(ctx);
        }
        if (ret == BSL_UIO_IO_EOF) {
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_PARSE);
            return BSL_HTTP_ERR_RESP_PARSE;
        }
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_IO);
        return BSL_HTTP_ERR_IO;
    }
}

/* The body is at the maxRespLen cap and close-delimited (a Content-Length body
 * completes at or below the cap): probe for EOF so a body of exactly maxRespLen
 * is accepted. Returns PROGRESS (state DONE) on EOF, an error, or in-progress. */
static int32_t HttpProbeRespBodyEof(HITLS_HTTP_ReqCtx *ctx)
{
    /* Hard deadline: fail once the transfer has exceeded its allowed time. */
    if (HttpCheckDeadline(ctx) != 0) {
        return BSL_HTTP_ERR_TIMEOUT;
    }
    uint8_t probe;
    uint32_t probeLen = 0;
    int32_t ret = BSL_UIO_Read(ctx->uio, &probe, 1, &probeLen);
    if (ret == BSL_UIO_IO_EOF) {
        ctx->state = HITLS_HTTP_STATE_DONE;
        return BSL_SUCCESS;
    }
    if (ret == BSL_UIO_IO_BUSY) {
        return HttpInProgressOrTimeout(ctx);
    }
    if (ret == BSL_SUCCESS) {
        if (probeLen > 0) {
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_TOO_LARGE);
            return BSL_HTTP_ERR_RESP_TOO_LARGE;
        }
        return HttpInProgressOrTimeout(ctx);
    }
    BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_IO);
    return BSL_HTTP_ERR_IO;
}

static int32_t HttpReadResponseBody(HITLS_HTTP_ReqCtx *ctx)
{
    for (;;) {
        if (ctx->hasContentLength && ctx->respBodyLen >= ctx->respContentLength) {
            ctx->state = HITLS_HTTP_STATE_DONE;
            return BSL_SUCCESS;
        }
        uint32_t want = ctx->maxRespLen - ctx->respBodyLen;
        if (ctx->hasContentLength && want > ctx->respContentLength - ctx->respBodyLen) {
            want = ctx->respContentLength - ctx->respBodyLen;
        }
        if (want > HITLS_HTTP_READ_CHUNK) {
            want = HITLS_HTTP_READ_CHUNK;
        }
        if (want == 0) {
            return HttpProbeRespBodyEof(ctx);
        }
        /* Hard deadline: fail once the transfer has exceeded its allowed time. */
        if (HttpCheckDeadline(ctx) != 0) {
            return BSL_HTTP_ERR_TIMEOUT;
        }
        uint8_t chunk[HITLS_HTTP_READ_CHUNK];
        uint32_t readLen = 0;
        int32_t ret = BSL_UIO_Read(ctx->uio, chunk, want, &readLen);
        if (ret == BSL_SUCCESS) {
            if (readLen > 0) {
                int32_t appRet = HttpAppendRespBody(ctx, chunk, readLen);
                if (appRet != BSL_SUCCESS) {
                    return appRet;
                }
                continue;
            }
            return HttpInProgressOrTimeout(ctx);
        }
        if (ret == BSL_UIO_IO_BUSY) {
            return HttpInProgressOrTimeout(ctx);
        }
        if (ret == BSL_UIO_IO_EOF) {
            if (ctx->hasContentLength && ctx->respBodyLen < ctx->respContentLength) {
                BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_RESP_PARSE);
                return BSL_HTTP_ERR_RESP_PARSE;
            }
            ctx->state = HITLS_HTTP_STATE_DONE;
            return BSL_SUCCESS;
        }
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_IO);
        return BSL_HTTP_ERR_IO;
    }
}

/* Run the handler for the current state. A handler returns BSL_SUCCESS when it
 * advanced the state machine to a new phase (completion is detected by the
 * driver via state == DONE), BSL_HTTP_ERR_IN_PROGRESS when it is blocked on I/O,
 * or an error code. */
static int32_t HttpRunState(HITLS_HTTP_ReqCtx *ctx)
{
    switch (ctx->state) {
        case HITLS_HTTP_STATE_INIT:
            /* Leave the configuration phase and start the transfer: headers and
             * transfer settings can no longer be changed. */
            ctx->state = HITLS_HTTP_STATE_WRITE_HDR;
            return HttpWriteRequestHeader(ctx);
        case HITLS_HTTP_STATE_WRITE_HDR:
            return HttpWriteRequestHeader(ctx);
        case HITLS_HTTP_STATE_WRITE_REQ:
            return HttpWriteRequestBody(ctx);
        case HITLS_HTTP_STATE_FLUSH:
            return HttpFlush(ctx);
        case HITLS_HTTP_STATE_READ_HDR:
            return HttpReadResponseHeader(ctx);
        case HITLS_HTTP_STATE_READ_BODY:
            return HttpReadResponseBody(ctx);
        case HITLS_HTTP_STATE_DONE:
            /* Terminal state: the driver detects completion via state == DONE. */
            return BSL_SUCCESS;
        default:
            /* Only reachable on an internal invariant violation (state is always
             * one of the enum values above), not a caller parameter error. */
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_STATE);
            return BSL_HTTP_ERR_STATE;
    }
}

int32_t HITLS_HTTP_ReqCtxExchange(HITLS_HTTP_ReqCtx *ctx, const uint8_t **respBody, uint32_t *respLen)
{
    if (ctx == NULL) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    if (respBody == NULL || *respBody != NULL) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    if (respLen == NULL || *respLen != 0) {
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_PARAM);
        return BSL_HTTP_ERR_PARAM;
    }
    if (ctx->state == HITLS_HTTP_STATE_ERROR) {
        /* The error was pushed at the first failure; return it unchanged. */
        return ctx->errCode;
    }
    if (ctx->method == HITLS_HTTP_METHOD_POST && !ctx->reqSet) {
        /* A POST body must be configured with SetReq before the transfer; this
         * is a usage/state error, distinct from an invalid argument. */
        BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_REQ_NOT_SET);
        return BSL_HTTP_ERR_REQ_NOT_SET;
    }

    for (;;) {
        HITLS_HTTP_State prevState = ctx->state;
        int32_t r = HttpRunState(ctx);
        if (r == BSL_HTTP_ERR_IN_PROGRESS) {
            /* Would-block (EAGAIN convention): no progress was made, the caller
             * must poll again. Not an error. */
            return r;
        }
        if (r != BSL_SUCCESS) {
            ctx->errCode = r;
            ctx->state = HITLS_HTTP_STATE_ERROR;
            return r;
        }
        if (ctx->state == HITLS_HTTP_STATE_DONE) {
            uint32_t bodyLen = 0;
            const uint8_t *body = HttpGetRespBody(ctx, &bodyLen);
            *respBody = body;
            *respLen = bodyLen;
            return BSL_SUCCESS;
        }
        if (ctx->state == prevState) {
            /* A handler returned success without advancing the state machine: an
             * internal contract violation, reported as an error instead of a
             * busy loop. */
            BSL_ERR_PUSH_ERROR(BSL_HTTP_ERR_STATE);
            ctx->errCode = BSL_HTTP_ERR_STATE;
            ctx->state = HITLS_HTTP_STATE_ERROR;
            return BSL_HTTP_ERR_STATE;
        }
        continue;
    }
}

